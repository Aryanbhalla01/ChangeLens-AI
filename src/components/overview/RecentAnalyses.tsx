import { ArrowUpRight, FileCode2 } from "lucide-react";
import type { RecentAnalysis } from "../../types";

interface RecentAnalysesProps {
  items: RecentAnalysis[];
  onViewAll: () => void;
}

const riskBadge: Record<RecentAnalysis["riskLevel"], string> = {
  low: "border-green-500/20 bg-green-500/10 text-green-300",
  medium: "border-amber-500/20 bg-amber-500/10 text-amber-300",
  high: "border-orange-500/20 bg-orange-500/10 text-orange-300",
  critical: "border-red-500/20 bg-red-500/10 text-red-300",
};

export function RecentAnalyses({ items, onViewAll }: RecentAnalysesProps) {
  return (
    <section className="panel-card overflow-hidden" id="recent-analyses">
      <div className="flex items-center justify-between gap-3 px-5 py-4">
        <div>
          <h2 className="text-sm font-semibold text-slate-100">Recent analysis previews</h2>
          <p className="mt-1 text-[11px] text-slate-500">
            Example changes · not generated by an analyzer
          </p>
        </div>
        <button
          className="flex shrink-0 items-center gap-1 text-[11px] font-medium text-blue-300 hover:text-blue-200"
          onClick={onViewAll}
        >
          View all <ArrowUpRight size={13} />
        </button>
      </div>
      <div className="overflow-x-auto">
        <table className="w-full min-w-[620px] border-collapse text-left">
          <thead>
            <tr className="border-y border-line bg-sidebar/60 text-[10px] font-medium uppercase tracking-wider text-slate-600">
              <th className="px-5 py-2.5">Change</th>
              <th className="px-4 py-2.5">Branch</th>
              <th className="px-4 py-2.5">Files</th>
              <th className="px-4 py-2.5">Risk preview</th>
              <th className="px-5 py-2.5 text-right">Updated</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-line/70">
            {items.length > 0 ? (
              items.map((item) => (
                <tr className="transition-colors hover:bg-white/[0.015]" key={item.id}>
                  <td className="px-5 py-3.5">
                    <div className="flex items-center gap-3">
                      <span className="flex h-8 w-8 shrink-0 items-center justify-center rounded-lg border border-line bg-elevated text-slate-400">
                        <FileCode2 size={15} />
                      </span>
                      <div className="min-w-0">
                        <p className="max-w-[240px] truncate text-xs font-medium text-slate-200">
                          {item.title}
                        </p>
                        <p className="mt-1 text-[10px] text-slate-500">{item.repository}</p>
                      </div>
                    </div>
                  </td>
                  <td className="px-4 py-3.5 text-[11px] text-slate-400">{item.branch}</td>
                  <td className="px-4 py-3.5 text-[11px] text-slate-400">
                    {item.filesChanged} files
                  </td>
                  <td className="px-4 py-3.5">
                    <span
                      className={`inline-flex items-center gap-1.5 rounded-full border px-2 py-1 text-[10px] font-medium capitalize ${riskBadge[item.riskLevel]}`}
                    >
                      {item.riskLevel} · {item.riskScore}
                    </span>
                  </td>
                  <td className="px-5 py-3.5 text-right text-[10px] text-slate-500">
                    {item.time}
                  </td>
                </tr>
              ))
            ) : (
              <tr>
                <td className="px-5 py-9 text-center text-xs text-slate-500" colSpan={5}>
                  No demo changes match this search.
                </td>
              </tr>
            )}
          </tbody>
        </table>
      </div>
      <div className="border-t border-line px-5 py-3 text-[10px] leading-relaxed text-slate-600">
        Scores and labels are illustrative sample values, not calculated risk findings.
      </div>
    </section>
  );
}
